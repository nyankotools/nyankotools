/** 日本語の色名 → 区分の判別は RAW の配置で行う。重複する色名は最初のものを残す */
function buildColors(): TraditionalColor[] {
  const seen = new Set<string>();
  const out: TraditionalColor[] = [];
  for (const group of COLOR_GROUPS) {
    for (const row of RAW[group]) {
      const [name, reading, hexBody] = row.split('|');
      if (seen.has(name)) continue;
      seen.add(name);
      const hex = `#${hexBody}`;
      const rgb = hexToRgb(hex);
      if (!rgb) continue;
      out.push({
        name,
        reading,
        romaji: kanaToRomaji(reading, {
          style: 'hepburn',
          longVowel: 'omit',
          letterCase: 'lower',
        }),
        hex,
        rgb: `rgb(${rgb.r}, ${rgb.g}, ${rgb.b})`,
        group,
      });
    }
  }
  return out;
}

export const TRADITIONAL_COLORS: TraditionalColor[] = buildColors();

/** ひらがな化（カタカナ入力をひらがなに寄せる） */
function toHiragana(text: string): string {
  return text.replace(/[ァ-ヶ]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) - 0x60),
  );
}

/**
 * 色名・読み・ローマ字・HEXで検索する。空のクエリは全件、区分は 'all' で絞り込みなし。
 * HEXは「#」の有無を問わず部分一致する。
 */
export function filterColors(
  query: string,
  group: ColorGroup | 'all' = 'all',
  colors: TraditionalColor[] = TRADITIONAL_COLORS,
): TraditionalColor[] {
  const q = toHiragana(query.normalize('NFKC').trim().toLowerCase());
  const hexQuery =
    /^#?[0-9a-f]{3,6}$/.test(q) && (q.startsWith('#') || /\d/.test(q))
      ? q.replace(/^#/, '')
      : '';
  return colors.filter((c) => {
    if (group !== 'all' && c.group !== group) return false;
    if (q === '') return true;
    return (
      c.name.includes(q) ||
      c.reading.includes(q) ||
      c.romaji.includes(q) ||
      (hexQuery !== '' && c.hex.slice(1).includes(hexQuery))
    );
  });
}

function channelLuminance(value: number): number {
  const c = value / 255;
  return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}

/**
 * 背景HEXの上に載せる文字色（黒または白）を、WCAGのコントラスト比が高いほうで選ぶ。
 * 黒・白のどちらかは必ず4.5:1以上になる。
 */
export function readableTextColor(hex: string): '#000000' | '#ffffff' {
  const rgb = hexToRgb(hex);
  if (!rgb) return '#000000';
  const lum =
    0.2126 * channelLuminance(rgb.r) +
    0.7152 * channelLuminance(rgb.g) +
    0.0722 * channelLuminance(rgb.b);
  // 白: 1.05/(lum+0.05)、黒: (lum+0.05)/0.05 の大きいほう
  return 1.05 / (lum + 0.05) > (lum + 0.05) / 0.05 ? '#ffffff' : '#000000';
}
